#!/usr/bin/env python3
"""Build the single shared browser catalog from all registered novel sources.

Place ordinary book records in data/books.js or add a generated data/<slug>.js.
Every other data/*.js file is discovered automatically except reserved
configuration, analytics and compiled files. Never embed individual book IDs
or titles in website pages, analytics scripts, or ranking jobs.
"""
from pathlib import Path
import argparse

RESERVED = {"books.js", "catalog.js", "rankings.js", "analytics-config.js", "site-config.js"}

def sources(site: Path) -> list[Path]:
    folder = site / "data"
    base = folder / "books.js"
    if not base.is_file():
        raise FileNotFoundError(f"Missing base catalog: {base}")
    overlays = sorted(
        (p for p in folder.glob("*.js") if p.name not in RESERVED),
        key=lambda p: p.name.casefold()
    )
    return [base, *overlays]

def bundle(site: Path) -> str:
    parts = [
        "// Generated from all data/*.js novel sources by scripts/build_catalog.py.\n",
        "// Do not edit this file: edit data/books.js or add a data/<slug>.js file.\n",
    ]
    for file in sources(site):
        code = file.read_text(encoding="utf-8-sig").strip()
        if not code:
            raise ValueError(f"Empty novel source: {file.relative_to(site)}")
        parts.append(f"\n// Source: {file.relative_to(site).as_posix()}\n")
        parts.append(code + "\n")
    return "".join(parts)

def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--site", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--check", action="store_true", help="Fail if the built catalog is out of date")
    args = parser.parse_args()
    site = args.site.resolve()
    result = bundle(site)
    path = site / "data/catalog.js"
    if args.check:
        if not path.is_file() or path.read_text(encoding="utf-8") != result:
            parser.error("Catalog bundle is out of date: run python3 scripts/build_catalog.py")
        print("Shared catalog is up to date.")
        return
    if path.exists() and path.read_text(encoding="utf-8") == result:
        print("Shared catalog unchanged.")
        return
    path.write_text(result, encoding="utf-8")
    print(f"Updated data/catalog.js from {len(sources(site))} novel sources.")

if __name__ == "__main__":
    main()
